export function useT(lang: 'en' | 'cs') {
  return (key: UiKey, vars: Record<string, string | number> = {}) =>
    (ui[lang][key] ?? ui.en[key]).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}
